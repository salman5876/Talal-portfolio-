const dlg = document.getElementById('case-dialog'), body = document.getElementById('case-body');
const pad = n => String(n).padStart(2,'0');

function openCase(key){
  const c = CASES[key]; if(!c) return;
const imgs = key === 'muhammadi'
  ? [
      'Muhammadi Electronics/img 1.png',
      'Muhammadi Electronics/img 2.png',
      'Muhammadi Electronics/img 3.png',
      'Muhammadi Electronics/img 4.png'
    ].map(src => `<figure><img src="${src}" alt="Muhammadi Electronics project image" loading="lazy"></figure>`).join('')
  : key === 'islamabad'
  ? [
      'Islamabad Electronics/img 1.png',
      'Islamabad Electronics/img 2.png',
      'Islamabad Electronics/img 3.png',
      'Islamabad Electronics/img 4.png'
    ].map(src => `<figure><img src="${src}" alt="Islamabad Electronics project image" loading="lazy"></figure>`).join('')
  : key === 'musketeers'
  ? [
      'Musketeers/img 1.jpg',
      'Musketeers/img 2.jpg',
      'Musketeers/img 3.jpg',
      'Musketeers/img 4.jpg'
    ].map(src => `<figure><img src="${src}" alt="Musketeers project image" loading="lazy"></figure>`).join('')
  : [1, 2, 3, 4].map(i => `<figure><img src="images/${key}-${i}.jpg" alt="${c.title} frame ${i}" loading="lazy"></figure>`).join('');
  body.innerHTML = `
   <header class="cs-head">
     <p class="mono cs-kicker">Case study</p>
     <h2>${c.title}</h2>
     <p class="cs-hook">${c.hook}</p>
     <p class="cs-tag">${c.tag}</p>
     <dl class="cs-meta">${c.meta.map(([k,v])=>`<div><dt class="mono">${k}</dt><dd>${v}</dd></div>`).join('')}</dl>
   </header>
   ${c.sections.map((s,i)=>`
   <section class="cs-sec">
     <div class="cs-num" aria-hidden="true">${pad(i+1)}</div>
     <div class="cs-txt">
       <p class="mono cs-label">${s.l}</p>
       <h3>${s.h}</h3>
       ${(s.p||[]).map(t=>`<p>${t}</p>`).join('')}
       ${s.items?`<div class="cs-items">${s.items.map(([t,d])=>`<div><h4>${t}</h4><p>${d}</p></div>`).join('')}</div>`:''}
     </div>
   </section>
   ${i===1?`<div class="cs-gallery">${imgs}</div>`:''}`).join('')}
   <section class="cs-take">
     <p class="mono cs-label">The takeaway 💡</p>
     <h3>${c.take.h}</h3>
     <p>${c.take.p}</p>
     <dl>${c.take.lines.map(([k,v])=>`<div><dt class="mono">${k}</dt><dd>${v}</dd></div>`).join('')}</dl>
   </section>`;
  dlg.showModal(); dlg.scrollTop = 0; document.body.style.overflow='hidden';
}
document.querySelectorAll('[data-case]').forEach(b => b.addEventListener('click', () => openCase(b.dataset.case)));
document.getElementById('case-close').addEventListener('click', () => dlg.close());
dlg.addEventListener('close', () => { document.body.style.overflow=''; });
